#!/usr/bin/env python3
"""Generate the PC port's PSP import stubs from docs/imports.md.

Writes one C file per shim subsystem into src/platform/ plus src/platform/psp_imports.h
(prototypes and a table of every import). Each stub logs its first call through
psp_stub_hit() and returns 0. The files are meant to be edited by hand as imports get
real implementations, so existing files are never overwritten without --force.

Real PSP signatures aren't known here: stubs are declared `int32_t name(void)`. When game
code needs an import, give it its real signature in the subsystem file and the header.

Usage: gen_shim_stubs.py [--force] [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "imports.md"
OUT = ROOT / "src" / "platform"

# PSP library -> (shim file, subsystem description)
GROUPS = {
    "files": ("File I/O and UMD", ["IoFileMgrForUser", "sceUmdUser"]),
    "input": ("Controller input", ["sceCtrl"]),
    "threads": ("Kernel threads, sync, timing, interrupts",
                ["ThreadManForUser", "Kernel_Library", "InterruptManager", "sceSuspendForUser"]),
    "graphics": ("GE, display, DMA", ["sceGe_user", "sceDisplay", "sceDmac"]),
    "audio": ("Audio output and decoders", ["sceAudio", "sceSasCore", "sceAtrac3plus", "sceMp3"]),
    "video": ("MPEG movie playback", ["sceMpeg"]),
    "net": ("Ad hoc networking and WLAN",
            ["sceNet", "sceNetAdhoc", "sceNetAdhocctl", "sceNetAdhocMatching", "sceWlanDrv"]),
    "system": ("Memory, modules, process, utility dialogs, power, clock",
               ["SysMemUserForUser", "ModuleMgrForUser", "LoadExecForUser", "UtilsForUser",
                "StdioForUser", "sceUtility", "sceImpose", "scePower", "sceRtc"]),
}

LIB_RE = re.compile(r"^### `(\w+)` \(flags (0x[0-9A-Fa-f]+), (\d+) funcs\)")
ROW_RE = re.compile(r"^\| (0x[0-9A-F]+) \| (0x[0-9A-F]+) \| `(\w+)` \|")


def parse():
    libs, cur = {}, None
    for line in DOC.read_text().splitlines():
        if m := LIB_RE.match(line):
            cur = m[1]
            libs[cur] = {"count": int(m[3]), "funcs": []}
        elif cur and (m := ROW_RE.match(line)):
            libs[cur]["funcs"].append((int(m[2], 16), m[3]))
    for name, lib in libs.items():
        if len(lib["funcs"]) != lib["count"]:
            sys.exit(f"{name}: header says {lib['count']} funcs, found {len(lib['funcs'])}")
    return libs


def render_group(key, desc, libnames, libs):
    out = [f"/* PSP shim: {desc}.",
           f" * Generated by tools/gen_shim_stubs.py from docs/imports.md, then edited by hand.",
           " * Every function starts as a logging stub that returns 0. */",
           '#include "psp_imports.h"', '#include "psp_shim.h"', ""]
    for lib in libnames:
        out.append(f"/* ---- {lib} ({len(libs[lib]['funcs'])} imports) ---- */")
        out.append("")
        for nid, name in libs[lib]["funcs"]:
            out.append(f"int32_t {name}(void)")
            out.append("{")
            out.append(f'    PSP_STUB("{lib}", 0x{nid:08X});')
            out.append("    return 0;")
            out.append("}")
            out.append("")
    return "\n".join(out)


def render_header(libs):
    out = ["/* PSP imports used by the game (299 functions in 29 libraries).",
           " * Generated by tools/gen_shim_stubs.py from docs/imports.md. Signatures start as",
           " * (void) and get their real PSP signatures as each import is implemented. */",
           "#ifndef PSP_IMPORTS_H", "#define PSP_IMPORTS_H", "", "#include <stdint.h>", ""]
    for key, (desc, libnames) in GROUPS.items():
        out.append(f"/* {key}.c: {desc} */")
        for lib in libnames:
            for _, name in libs[lib]["funcs"]:
                out.append(f"int32_t {name}(void);")
        out.append("")
    out += ["typedef struct PspImport {", "    const char *library;", "    const char *name;",
            "    uint32_t nid;", "    const char *group;",
            "    void (*fn)(void); /* generic pointer, for --call-all-stubs only */", "} PspImport;", "",
            "extern const PspImport psp_imports[];", "extern const int psp_import_count;", "",
            "#endif", ""]
    return "\n".join(out)


def render_table(libs):
    out = ["/* Table of all PSP imports. Generated by tools/gen_shim_stubs.py. */",
           '#include "psp_imports.h"', "", "const PspImport psp_imports[] = {"]
    n = 0
    for key, (_, libnames) in GROUPS.items():
        for lib in libnames:
            for nid, name in libs[lib]["funcs"]:
                out.append(f'    {{"{lib}", "{name}", 0x{nid:08X}, "{key}", (void (*)(void)){name}}},')
                n += 1
    out += ["};", "", f"const int psp_import_count = {n};", ""]
    return "\n".join(out)


def main(argv):
    force = "--force" in argv
    libs = parse()
    grouped = [lib for _, libnames in GROUPS.values() for lib in libnames]
    missing = sorted(set(libs) - set(grouped))
    if missing or len(grouped) != len(set(grouped)):
        sys.exit(f"libraries not assigned to exactly one group: {missing}")
    total = sum(len(l["funcs"]) for l in libs.values())
    if "--check" in argv:
        print(f"{len(libs)} libraries, {total} imports, {len(GROUPS)} groups")
        return
    files = {OUT / "psp_imports.h": render_header(libs), OUT / "psp_import_table.c": render_table(libs)}
    for key, (desc, libnames) in GROUPS.items():
        files[OUT / f"{key}.c"] = render_group(key, desc, libnames, libs)
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        if path.exists() and not force:
            print(f"skip {path.relative_to(ROOT)} (exists; --force to overwrite)")
            continue
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    print(f"{total} imports in {len(GROUPS)} groups")


if __name__ == "__main__":
    main(sys.argv[1:])
