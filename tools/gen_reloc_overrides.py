#!/usr/bin/env python3
"""Generate splat reloc overrides for false symbol references, using the PRX relocation table.

The EBOOT is a relocatable PRX, so every real pointer has an entry in a PSP relocation
section (sh_type 0x700000A0). spimdisasm can't see those tables and guesses symbols from
lui/lo pairs and data words, which produces bogus symbols such as pointers into the middle
of functions (these break label emission) or ASCII built from immediates.

This script scans splat's asm output for %hi/%lo/.word references to auto-named symbols at
ROM offsets that have *no* PRX relocation, and writes overrides that print them as
constants, e.g. `%hi(0x0000B5A4)` / `%lo(0x0000B5A4)` / `.word 0x...`. The bytes stay the
same; only the bogus symbol goes away.

The output is cumulative: existing entries are kept, since after a re-split the overridden
lines no longer look like symbol references.

It also writes OUT_TXT with "_ignore" before the extension: splat symbol entries with
`ignore:True` for each bogus address that is never the target of a real (relocated)
reference. Without these spimdisasm still creates the symbol internally (e.g. an `alabel`
mid-function), which can swallow local branch labels.

Usage: gen_reloc_overrides.py ELF ASM_DIR OUT_TXT [MANUAL_TXT ...]
"""
import re
import struct
import sys
from pathlib import Path

PSP_REL = 0x700000A0
R_MIPS_32, R_MIPS_HI16, R_MIPS_LO16 = 2, 5, 6

LINE = re.compile(r"^\s*/\*\s*(?P<rom>[0-9A-F]+)\s+[0-9A-F]+\s+[0-9A-F]{8}\s*\*/\s*(?P<body>.*)$")
SYM = r"(?P<name>(?:D|func|jtbl|L|STR)_(?P<addr>[0-9A-F]{8}))(?:\s*\+\s*(?P<add>0x[0-9A-F]+|\d+))?"
HILO = re.compile(r"%(?P<kind>hi|lo)\(" + SYM + r"\)")
WORD = re.compile(r"^\.word\s+" + SYM + r"\s*$")


def load_relocs(path):
    d = Path(path).read_bytes()
    phoff, shoff = struct.unpack_from("<II", d, 0x1C)[0], struct.unpack_from("<I", d, 0x20)[0]
    phnum, shnum = struct.unpack_from("<H", d, 0x2C)[0], struct.unpack_from("<H", d, 0x30)[0]
    segs = [struct.unpack_from("<8I", d, phoff + 32 * i) for i in range(phnum)]
    rom_sites = {}  # rom offset -> reloc type
    for i in range(shnum):
        sh = struct.unpack_from("<10I", d, shoff + 40 * i)
        if sh[1] != PSP_REL:
            continue
        for k in range(sh[5] // 8):
            off, info = struct.unpack_from("<II", d, sh[4] + 8 * k)
            ofs_base = (info >> 8) & 0xFF
            seg = segs[ofs_base]
            rom = seg[1] + off  # p_offset + offset within segment
            rom_sites[rom] = info & 0xFF
    return rom_sites


def main(elf, asm_dir, out, *manual):
    relocs = load_relocs(elf)
    entries = {}
    outp = Path(out)
    taken = set()
    for m in manual:
        p = Path(m)
        if p.exists():
            taken |= {int(x, 16) for x in re.findall(r"rom:(0x[0-9A-Fa-f]+)", p.read_text())}
    if outp.exists():
        for line in outp.read_text().splitlines():
            r = re.search(r"rom:(0x[0-9A-Fa-f]+)", line)
            if r:
                entries[int(r.group(1), 16)] = line
    added = 0
    real = set()
    for s in sorted(Path(asm_dir).rglob("*.s")):
        for line in s.read_text().splitlines():
            g = re.match(r"^\s*glabel\s+\w+_([0-9A-F]{8})\b", line) or re.search(r"\bjal\s+\w+_([0-9A-F]{8})\b", line)
            if g:
                real.add(int(g.group(1), 16))  # function starts / call targets are never banned
            m = LINE.match(line)
            if not m:
                continue
            rom = int(m["rom"], 16)
            if rom in taken or rom in entries:
                continue
            body = m["body"]
            h = HILO.search(body)
            w = None if h else WORD.match(body)
            ref = h or w
            if not ref:
                continue
            want = R_MIPS_32 if w else (R_MIPS_HI16 if h["kind"] == "hi" else R_MIPS_LO16)
            if relocs.get(rom) == want:
                real.add(int(ref["addr"], 16))
                continue  # real pointer
            value = int(ref["addr"], 16) + (int(ref["add"], 0) if ref["add"] else 0)
            kind = "MIPS_32" if w else ("MIPS_HI16" if h["kind"] == "hi" else "MIPS_LO16")
            entries[rom] = f"rom:0x{rom:06X} reloc:{kind} symbol:0x{value:08X} // was {ref['name']}"
            added += 1
    outp.write_text(
        "// AUTO-GENERATED by tools/gen_reloc_overrides.py - references with no PRX relocation\n"
        + "".join(entries[k] + "\n" for k in sorted(entries))
    )
    ign = outp.with_name(outp.stem + "_ignore" + outp.suffix)
    old_real = set()
    if ign.exists():
        old_real = {int(x, 16) for x in re.findall(r"^// real (0x[0-9A-F]+)", ign.read_text(), re.M)}
    real |= old_real
    bogus = {int(re.search(r"symbol:(0x[0-9A-F]+)", e).group(1), 16) for e in entries.values()}
    bogus |= {int(re.search(r"// was \w+_([0-9A-F]{8})", e).group(1), 16) for e in entries.values()}
    ign.write_text(
        "// AUTO-GENERATED by tools/gen_reloc_overrides.py - addresses only reached by false references\n"
        + "".join(f"ignored_{a:08X} = 0x{a:08X}; // ignore:True\n" for a in sorted(bogus - real))
        + "".join(f"// real 0x{a:08X}\n" for a in sorted(real))
    )
    print(f"{out}: {len(entries)} overrides ({added} new); {ign}: {len(bogus - real)} ignored, {len(real)} real targets")
    return added


if __name__ == "__main__":
    main(*sys.argv[1:])
